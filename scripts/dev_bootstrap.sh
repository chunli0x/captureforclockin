#!/usr/bin/env bash
# Capture backend — dev-only bootstrap for a fresh clone.
#
#   ./scripts/dev_bootstrap.sh
#
# What it does (idempotent; safe to re-run):
#   1. Creates backend/.venv and installs backend/requirements-seeker.txt.
#   2. Generates THROWAWAY DEV-ONLY secrets and writes backend/.env:
#        - a random SEEKER_OPERATOR_KEY (>= 32 chars)
#        - a random SEEKER_MEDIA_KEY (base64 of 32 random bytes)
#        - a freshly generated throwaway devnet keypair (verifier.dev.json)
#      These are NOT the real operator/media/verifier keys — the real verifier
#      authorizes every attestation and is installed out of band, never here.
#   3. Applies the database schema via the existing migration path.
#
# The script never overwrites an existing backend/.env or verifier.dev.json,
# so it will not clobber a real deployment's keys.
set -euo pipefail

REPO_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
BACKEND_DIR="$REPO_DIR/backend"
VENV="$BACKEND_DIR/.venv"
ENV_FILE="$BACKEND_DIR/.env"
VERIFIER_DEV="$BACKEND_DIR/verifier.dev.json"

PUBLIC_PROGRAM_ID="5TiDwP86k95yfQWzExrPTj5qcKxED99z8pW9fN81u5SV"
PUBLIC_SKR_MINT="3aGKaVL7GpcTcTuKjkyirnVeyNG1JGFNyGGueu8mAGbM"

# Database: default to the docker-compose PostgreSQL, but allow callers to
# override (e.g. SEEKER_LOCAL_SQLITE=true SEEKER_DATABASE_URL=sqlite:///./seeker.db).
DB_URL="${SEEKER_DATABASE_URL:-postgresql+psycopg://seeker:seeker@localhost:5432/seeker}"
LOCAL_SQLITE="${SEEKER_LOCAL_SQLITE:-false}"

cd "$BACKEND_DIR"

# Python interpreter for the venv. Override with e.g. `PYTHON=python3.11`.
PY="${PYTHON:-python3}"

# --- 1. Python venv + dependencies -----------------------------------------
if [[ ! -x "$VENV/bin/python" ]]; then
  echo "[1/4] creating venv at $VENV (using $PY)"
  "$PY" -m venv "$VENV"
fi
echo "[1/4] installing dependencies (requirements-seeker.txt)"
"$VENV/bin/pip" install --quiet -r requirements-seeker.txt

# --- 2. Throwaway verifier keypair (dev-only, NOT the real verifier) -------
if [[ ! -f "$VERIFIER_DEV" ]]; then
  echo "[2/4] generating throwaway dev-only verifier keypair -> verifier.dev.json"
  "$VENV/bin/python" - <<'PYEOF'
from solders.keypair import Keypair
import json

kp = Keypair()
# Solana keypair JSON: [32 secret bytes, 32 public bytes] as ints. This is the
# exact format seeker.chain.Chain reads via Keypair.from_bytes(bytes(json.loads(...))).
json.dump(list(bytes(kp)), open("verifier.dev.json", "w"))
print("  dev verifier pubkey:", str(kp.pubkey()))
PYEOF
  chmod 600 "$VERIFIER_DEV"
else
  echo "[2/4] verifier.dev.json already exists; leaving it untouched"
fi

# --- 3. backend/.env with throwaway secrets + public constants ---------------
if [[ -f "$ENV_FILE" ]]; then
  echo "[3/4] $ENV_FILE already exists; leaving it untouched"
else
  echo "[3/4] generating dev-only secrets -> .env"
  OPERATOR_KEY="$("$VENV/bin/python" -c 'import secrets; print(secrets.token_urlsafe(48))')"
  MEDIA_KEY="$("$VENV/bin/python" -c 'import base64, os; print(base64.b64encode(os.urandom(32)).decode())')"

  cat > "$ENV_FILE" <<EOF
# Generated by scripts/dev_bootstrap.sh — DEV-ONLY throwaway secrets.
# Never commit this file.
SEEKER_DATABASE_URL=$DB_URL
SEEKER_LOCAL_SQLITE=$LOCAL_SQLITE
SEEKER_OPERATOR_KEY=$OPERATOR_KEY
SEEKER_MEDIA_KEY=$MEDIA_KEY
SEEKER_PROGRAM_ID=$PUBLIC_PROGRAM_ID
SEEKER_SKR_MINT=$PUBLIC_SKR_MINT
SEEKER_RPC_URL=https://api.devnet.solana.com
SEEKER_CLUSTER=devnet
SEEKER_VERIFIER_KEY_FILE=verifier.dev.json
SEEKER_DOMAIN=localhost
SEEKER_SIGHTENGINE_USER=
SEEKER_SIGHTENGINE_SECRET=
SEEKER_HIVE_KEY=
EOF
  chmod 600 "$ENV_FILE"
fi

# --- 4. Apply schema via the existing migration path -------------------------
echo "[4/4] applying database schema (python -m seeker.migrate)"
set -a
# shellcheck disable=SC1091
. "$ENV_FILE"
set +a

MIGRATED=0
for attempt in 1 2 3; do
  if "$VENV/bin/python" -m seeker.migrate; then
    MIGRATED=1
    break
  fi
  echo "  migrate attempt $attempt failed; retrying in 5s (is the database up?)" >&2
  sleep 5
done
if [[ "$MIGRATED" != "1" ]]; then
  echo "migrate failed after 3 attempts. If using PostgreSQL, run 'docker compose up -d' first." >&2
  exit 1
fi

cat <<'EOF'

==============================================================
  Dev bootstrap complete.
  Next:  cd backend && .venv/bin/uvicorn seeker.api:production_app --factory --env-file .env
  Then:  curl -s http://localhost:8000/health
==============================================================
EOF
